import { jsPDF } from 'jspdf';
import {
  ForensicReport,
  ProctoringTimelineEvent,
} from '../types/proctoring.types';

/**
 * Pure jsPDF generator for proctoring forensic reports. No browser APIs — it
 * runs identically in Node (for testing) and the browser (for download).
 *
 * Layout: A4, 48pt margins, navy brand header, integrity summary, flags,
 * paginated event timeline, numbered footer.
 */

export interface PdfExamMeta {
  title?: string;
  subject_name?: string;
  class_name?: string;
  status?: string;
  brand?: string;
}

const PAGE_W = 595.28;
const PAGE_H = 841.89;
const MARGIN = 48;
const CONTENT_W = PAGE_W - MARGIN * 2;
const FOOTER_H = 40;

const NAVY: [number, number, number] = [0x00, 0x2a, 0x56];
const RED: [number, number, number] = [0xdc, 0x26, 0x26];
const GREEN: [number, number, number] = [0x05, 0x96, 0x69];
const AMBER: [number, number, number] = [0xd9, 0x77, 0x06];
const SLATE: [number, number, number] = [0x33, 0x41, 0x55];
const SLATE_LIGHT: [number, number, number] = [0x64, 0x74, 0x8b];
const BG: [number, number, number] = [0xf1, 0xf5, 0xf9];
const ZEBRA: [number, number, number] = [0xf8, 0xfa, 0xfc];
const WHITE: [number, number, number] = [0xff, 0xff, 0xff];

const EVENT_LABELS: Record<string, string> = {
  tab_switch: 'Tab switch',
  tab_return: 'Tab return',
  window_blur: 'Window blur',
  window_focus: 'Window focus',
  copy_attempt: 'Copy attempt',
  paste_attempt: 'Paste attempt',
  cut_attempt: 'Cut attempt',
  right_click: 'Right-click',
  fullscreen_exit: 'Fullscreen exit',
  devtools: 'Developer tools',
  answer_change: 'Answer change',
  suspicious_speed: 'Suspicious speed',
  device_switch: 'Device switch',
  exam_start: 'Exam start',
  exam_submit: 'Exam submit',
};

const pad2 = (n: number) => String(n).padStart(2, '0');

/**
 * jsPDF's built-in fonts are WinAnsi-encoded — characters outside that set
 * (₦, emoji, exotic scripts) render as garbage or throw. Sanitize every string
 * that reaches doc.text() so reports survive real-world names and details.
 */
const toWinAnsi = (input: unknown): string => {
  const s = String(input ?? '');
  let out = '';
  for (const ch of s) {
    if (ch === '₦') out += 'N';
    else if (ch === '–' || ch === '—') out += '-';
    else if (ch === '‘' || ch === '’' || ch === "'" || ch === '′') out += "'";
    else if (ch === '“' || ch === '”' || ch === '"') out += '"';
    else if (ch === '…') out += '...';
    else if (ch === '·' || ch === '•') out += '.';
    else if (ch.charCodeAt(0) < 32 || ch.charCodeAt(0) > 126) out += ' ';
    else out += ch;
  }
  return out;
};

/** Deterministic timestamp formatting (no locale dependence). */
const fmtDate = (iso: string | null | undefined): string => {
  if (!iso) return '—';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '—';
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return `${months[d.getMonth()]} ${pad2(d.getDate())}, ${d.getFullYear()} ${pad2(d.getHours())}:${pad2(d.getMinutes())}`;
};

const severityColor = (severity: number): [number, number, number] =>
  severity >= 6 ? RED : severity >= 3 ? AMBER : SLATE_LIGHT;

const levelColor = (level: string): [number, number, number] => {
  switch (level) {
    case 'High':
      return GREEN;
    case 'Moderate':
      return AMBER;
    case 'Critical':
      return RED;
    default:
      return SLATE;
  }
};

interface Cursor {
  y: number;
  page: number;
}

/** Build the paginated A4 forensic report. */
export function buildForensicPdf(report: ForensicReport, meta: PdfExamMeta = {}): jsPDF {
  const doc = new jsPDF({ unit: 'pt', format: 'a4', compress: true });
  const brand = meta.brand || 'Elite CBT';
  const ref = `${report.exam_id.slice(0, 8)}/${report.admission_no}`;
  const generatedAt = fmtDate(new Date().toISOString());
  const safeRef = toWinAnsi(ref);

  const cursor: Cursor = { y: 0, page: 1 };
  const totalEvents = report.timeline.length;

  const drawFooter = () => {
    const pageCount = doc.getNumberOfPages();
    for (let p = 1; p <= pageCount; p++) {
      doc.setPage(p);
      doc.setDrawColor(0xcb, 0xd5, 0xe1);
      doc.setLineWidth(0.7);
      doc.line(MARGIN, PAGE_H - FOOTER_H + 8, PAGE_W - MARGIN, PAGE_H - FOOTER_H + 8);
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(...SLATE_LIGHT);
      doc.text(`Page ${p} of ${pageCount}`, MARGIN, PAGE_H - FOOTER_H + 22);
      doc.text(`Generated by ${brand} · Report ${ref} · ${generatedAt}`, PAGE_W - MARGIN, PAGE_H - FOOTER_H + 22, {
        align: 'right',
      });
    }
    doc.setPage(cursor.page);
  };

  /** Move to a fresh page, re-draw the section header rule if desired. */
  const ensureSpace = (height: number) => {
    if (cursor.y + height > PAGE_H - FOOTER_H - 20) {
      doc.addPage();
      cursor.page = doc.getNumberOfPages();
      cursor.y = MARGIN;
    }
  };

  const sectionTitle = (label: string) => {
    ensureSpace(34);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11.5);
    doc.setTextColor(...NAVY);
    doc.text(label.toUpperCase(), MARGIN, cursor.y);
    doc.setDrawColor(...NAVY);
    doc.setLineWidth(1.4);
    doc.line(MARGIN, cursor.y + 5, MARGIN + 36, cursor.y + 5);
    cursor.y += 18;
  };

  const infoRow = (label: string, value: string, valueColor: [number, number, number] = SLATE) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9.5);
    doc.setTextColor(...SLATE_LIGHT);
    doc.text(label, MARGIN + 8, cursor.y);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...valueColor);
    const lines = doc.splitTextToSize(toWinAnsi(value), CONTENT_W - 170) as string[];
    doc.text(lines, MARGIN + 170, cursor.y);
    cursor.y += Math.max(lines.length, 1) * 13 + 4;
  };

  // ── Header band ───────────────────────────────────────────────────────────
  doc.setFillColor(...NAVY);
  doc.rect(0, 0, PAGE_W, 96, 'F');
  doc.setTextColor(...WHITE);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text('PROCTORING FORENSIC REPORT', MARGIN, 42);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(0xbf, 0xdbf, 0xea);
  doc.text('Computer-Based Test · Exam Integrity Record', MARGIN, 62);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(...WHITE);
  doc.text(brand, PAGE_W - MARGIN, 42, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Ref: ${safeRef}`, PAGE_W - MARGIN, 60, { align: 'right' });
  doc.text(`Generated: ${generatedAt}`, PAGE_W - MARGIN, 74, { align: 'right' });

  cursor.y = 122;

  // ── Exam & candidate details ──────────────────────────────────────────────
  sectionTitle('Report Details');
  doc.setFillColor(...BG);
  doc.rect(MARGIN, cursor.y, CONTENT_W, 124, 'F');
  infoRow('Examination', meta.title || '—');
  infoRow('Subject / Class', [meta.subject_name, meta.class_name].filter(Boolean).join(' · ') || '—');
  infoRow('Exam Reference', report.exam_id);
  infoRow('Candidate', report.student_name ? `${report.student_name} (${report.admission_no})` : report.admission_no);

  const session = report.sessions[0];
  const deviceInfo = session?.device_info as Record<string, unknown> | null | undefined;
  infoRow(
    'Device',
    deviceInfo
      ? typeof deviceInfo.user_agent === 'string'
        ? deviceInfo.user_agent.length > 80
          ? `${deviceInfo.user_agent.slice(0, 80)}…`
          : deviceInfo.user_agent
        : JSON.stringify(deviceInfo).slice(0, 80)
      : '—'
  );
  infoRow('Network IP', session?.ip_address || '—');
  cursor.y += 8;

  // ── Integrity summary ─────────────────────────────────────────────────────
  sectionTitle('Integrity Assessment');
  const level = report.integrity.level;
  const lvlColor = levelColor(level);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(44);
  doc.setTextColor(...lvlColor);
  doc.text(String(report.integrity.score), MARGIN, cursor.y + 40);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(`/ 100 · ${level}`, MARGIN + 92, cursor.y + 40);

  // score bar
  doc.setFillColor(...BG);
  doc.rect(MARGIN, cursor.y + 50, CONTENT_W, 8, 'F');
  doc.setFillColor(...lvlColor);
  doc.rect(MARGIN, cursor.y + 50, (CONTENT_W * Math.max(0, Math.min(100, report.integrity.score))) / 100, 8, 'F');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...SLATE_LIGHT);
  doc.text(`${report.event_count} recorded event${report.event_count === 1 ? '' : 's'}`, MARGIN, cursor.y + 74);
  cursor.y += 92;

  // event counts
  const counts = Object.entries(report.integrity.event_counts).filter(([, c]) => c > 0);
  if (counts.length > 0) {
    let cx = MARGIN;
    const chipH = 20;
    counts.forEach(([type, count]) => {
      const label = `${EVENT_LABELS[type] || type} ×${count}`;
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8.5);
      doc.setTextColor(...SLATE);
      doc.setFillColor(...ZEBRA);
      const w = doc.getTextWidth(label) + 18;
      if (cx + w > PAGE_W - MARGIN) {
        cx = MARGIN;
        cursor.y += chipH + 6;
      }
      doc.roundedRect(cx, cursor.y, w, chipH, 4, 4, 'F');
      doc.text(label, cx + 9, cursor.y + 13);
      cx += w + 6;
    });
    cursor.y += 34;
  }

  // ── Flags ─────────────────────────────────────────────────────────────────
  sectionTitle('Integrity Flags');
  if (report.integrity.flags.length > 0) {
    report.integrity.flags.forEach((flag) => {
      ensureSpace(24);
      doc.setFillColor(...RED);
      doc.circle(MARGIN + 5, cursor.y - 3, 3, 'F');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(...RED);
      doc.text(toWinAnsi(flag), MARGIN + 16, cursor.y);
      cursor.y += 17;
    });
  } else {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(...GREEN);
    doc.text('No integrity flags raised for this attempt.', MARGIN, cursor.y);
    cursor.y += 17;
  }
  cursor.y += 10;

  // ── Timeline table ────────────────────────────────────────────────────────
  sectionTitle('Event Timeline');
  const cols = {
    num: 26,
    event: 140,
    severity: 62,
    time: 118,
    details: CONTENT_W - 26 - 140 - 62 - 118,
  };
  const rowHeaderY = cursor.y;
  doc.setFillColor(...NAVY);
  doc.rect(MARGIN, rowHeaderY, CONTENT_W, 20, 'F');
  doc.setTextColor(...WHITE);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.text('#', MARGIN + 8, rowHeaderY + 13);
  doc.text('Event', MARGIN + cols.num + 8, rowHeaderY + 13);
  doc.text('Impact', MARGIN + cols.num + cols.event + 8, rowHeaderY + 13);
  doc.text('Timestamp', MARGIN + cols.num + cols.event + cols.severity + 8, rowHeaderY + 13);
  doc.text('Details', MARGIN + cols.num + cols.event + cols.severity + cols.time + 8, rowHeaderY + 13);
  cursor.y = rowHeaderY + 20;

  if (totalEvents === 0) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(...SLATE_LIGHT);
    doc.text('No proctoring events recorded for this attempt.', MARGIN + 8, cursor.y + 14);
    cursor.y += 30;
  } else {
    report.timeline.forEach((ev: ProctoringTimelineEvent, i: number) => {
      const detailText = ev.details
        ? ev.event_type === 'suspicious_speed' && typeof ev.details.avg_seconds_per_question === 'number'
          ? `${ev.details.avg_seconds_per_question}s/question · ${ev.details.questions ?? '?'} questions`
          : JSON.stringify(ev.details)
        : '';
      const wrapped = doc.splitTextToSize(detailText, cols.details - 14) as string[];
      const rowH = Math.max(19, wrapped.length * 11 + 10);
      ensureSpace(rowH + 4);

      // zebra
      if (i % 2 === 1) {
        doc.setFillColor(...ZEBRA);
        doc.rect(MARGIN, cursor.y, CONTENT_W, rowH, 'F');
      }

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(...SLATE);
      doc.text(String(i + 1), MARGIN + 8, cursor.y + 12);

      doc.setFont('helvetica', 'bold');
      doc.setTextColor(...SLATE);
      doc.text(toWinAnsi(EVENT_LABELS[ev.event_type] || ev.event_type), MARGIN + cols.num + 8, cursor.y + 12);

      doc.setFont('helvetica', 'bold');
      doc.setTextColor(...severityColor(ev.severity));
      doc.text(ev.severity > 0 ? `−${ev.severity}` : '0', MARGIN + cols.num + cols.event + 8, cursor.y + 12);

      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...SLATE_LIGHT);
      doc.text(fmtDate(ev.occurred_at), MARGIN + cols.num + cols.event + cols.severity + 8, cursor.y + 12);

      if (wrapped.length > 0) {
        doc.setTextColor(...SLATE_LIGHT);
        doc.text(wrapped, MARGIN + cols.num + cols.event + cols.severity + cols.time + 8, cursor.y + 12);
      }

      cursor.y += rowH;
    });
  }

  // ── Conclusion / certification note ───────────────────────────────────────
  cursor.y += 6;
  ensureSpace(90);
  sectionTitle('Certification');
  doc.setFillColor(...BG);
  const noteY = cursor.y;
  doc.rect(MARGIN, noteY, CONTENT_W, 56, 'F');
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...SLATE);
  const note = doc.splitTextToSize(
    'This report was generated automatically by the platform from server-authoritative exam session data. ' +
      'Integrity scores are advisory; event severity weights are assigned server-side. ' +
      'For verification, quote the report reference above.',
    CONTENT_W - 24
  ) as string[];
  doc.text(note, MARGIN + 12, noteY + 18);

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...NAVY);
  doc.text(`Report Reference: ${safeRef}`, MARGIN + 12, noteY + 18 + note.length * 11 + 8);

  drawFooter();
  return doc;
}

const safeFilePart = (s: string) => s.replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'unknown';

/** Generate and trigger a browser download of the forensic PDF. */
export function downloadForensicPdf(report: ForensicReport, meta: PdfExamMeta = {}) {
  const doc = buildForensicPdf(report, meta);
  const studentPart = safeFilePart(report.student_name || report.admission_no);
  const datePart = new Date().toISOString().slice(0, 10);
  const filename = `forensic-${studentPart}-${report.exam_id.slice(0, 8)}-${datePart}.pdf`;
  doc.save(filename);
  return filename;
}
